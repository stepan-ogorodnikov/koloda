use koloda::domain::seed_ids::{
    SEED_ALGORITHM_COMPLEX_ID, SEED_ALGORITHM_SIMPLE_ID, SEED_TEMPLATE_REVEAL_BACK_FIELD_ID,
    SEED_TEMPLATE_REVEAL_FRONT_FIELD_ID, SEED_TEMPLATE_REVEAL_ID, SEED_TEMPLATE_TYPE_BACK_FIELD_ID,
    SEED_TEMPLATE_TYPE_FRONT_FIELD_ID, SEED_TEMPLATE_TYPE_ID,
};

/// Pins the well-known seed UUIDv7 literals shared with `@koloda/app` `seed-ids.ts`.
#[test]
fn seed_ids_match_the_committed_literals() {
    assert_eq!(SEED_ALGORITHM_SIMPLE_ID, "01a08376-dc00-7001-8000-000000000100");
    assert_eq!(SEED_ALGORITHM_COMPLEX_ID, "01a08376-dc00-7002-8000-000000000200");
    assert_eq!(SEED_TEMPLATE_TYPE_ID, "01a08376-dc00-7003-8000-000000000300");
    assert_eq!(SEED_TEMPLATE_REVEAL_ID, "01a08376-dc00-7004-8000-000000000400");
    assert_eq!(
        SEED_TEMPLATE_TYPE_FRONT_FIELD_ID,
        "01a08376-dc00-7005-8000-000000000500"
    );
    assert_eq!(SEED_TEMPLATE_TYPE_BACK_FIELD_ID, "01a08376-dc00-7006-8000-000000000600");
    assert_eq!(
        SEED_TEMPLATE_REVEAL_FRONT_FIELD_ID,
        "01a08376-dc00-7007-8000-000000000700"
    );
    assert_eq!(
        SEED_TEMPLATE_REVEAL_BACK_FIELD_ID,
        "01a08376-dc00-7008-8000-000000000800"
    );
}
